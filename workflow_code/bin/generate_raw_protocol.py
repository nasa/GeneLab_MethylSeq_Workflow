#!/usr/bin/env python
"""
This script generates a protocol text file for GeneLab Methyl-seq raw data.
It reads software versions from an MD file generated upstream.
"""

import argparse
import os
import sys
from datetime import datetime

def parse_args():
    parser = argparse.ArgumentParser(description='Generate protocol file for GeneLab Methyl-Seq raw data')
    parser.add_argument('--outdir', required=True,
                        help='Output directory for the protocol file')
    parser.add_argument('--software_table', required=True,
                        help='Path to MD file containing software versions')
    parser.add_argument('--assay_suffix', default='',
                        help='Suffix for the assay type')
    parser.add_argument('--raw_merged', action="store_true",
                        help='Passed only when for datasets that require merging of raw fastq files')
    return parser.parse_args()


def parse_software_versions(md_file):
    versions = {}
    with open(md_file, 'r') as f:
        for line in f:
            if line.startswith('|') and not line.startswith('|:'):
                parts = [p.strip() for p in line.strip().strip('|').split('|')]
                if len(parts) >= 2 and parts[0] not in ('Program', ''):
                    versions[parts[0]] = parts[1]
    return versions


def generate_protocol_content(args, software_versions):
    # Get current date
    current_date = datetime.now().strftime("%Y-%m-%d")
    
    # Create header
    header = f"# GeneLab Methyl-Seq Raw Data Generation Protocol{args.assay_suffix}\n"
    header += f"# Date: {current_date}\n\n"
    
    description = ""
    if args.raw_merged:
        description += f"Merged raw reads files were generated by concatenating the data for each sample into forward and reverse raw reads files. "
    
    fastqc_version = software_versions.get('FastQC', 'Not found')
    multiqc_version = software_versions.get('MultiQC', 'Not found')

    description += f"Quality assessment of reads was performed with FastQC (version {fastqc_version}) and reports were combined with MultiQC (version {multiqc_version})."
    
    
    # Add paragraph break after the protocol text
    description += "\n"
    
    # Combine all sections
    content = header + description
    
    return content


def main():
    args = parse_args()
    
    # Read software versions from MD file
    software_versions = parse_software_versions(args.software_table)
    
    # Generate protocol content
    protocol_content = generate_protocol_content(args, software_versions)
    
    # Write to output file
    output_file = os.path.join(args.outdir, f"raw_data_protocol{args.assay_suffix}.txt")
    try:
        with open(output_file, 'w') as f:
            f.write(protocol_content)
        print(f"Protocol file generated successfully: {output_file}")
    except Exception as e:
        sys.stderr.write(f"Error writing protocol file: {e}\n")
        sys.exit(1)

if __name__ == "__main__":
    main()